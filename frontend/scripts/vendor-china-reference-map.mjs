import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { get } from 'node:https'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const SOURCE_URL = 'https://registry.npmjs.org/@svg-maps/china/-/china-2.0.0.tgz'
const EXPECTED_SHA1 = '853b3c7eba2762637fcde433decc9611d32f3325'
const EXPECTED_SHA256 = 'c294cb2f3478423d6add28fcec0e185a82cc3d866746e28a524ac5b9214f5e05'
const EXPECTED_INTEGRITY = 'sha512-/B0a4hYJHRtfcUG+x6BudQFWhLQyPoaN2WbqfdEeWeXnwef6oXaE93Msrq2odu72c09vE+G4Ds9+n60Qsr4p1g=='
const EXPECTED_VIEWBOX = '0 0 774 569'
const EXPECTED_FEATURE_COUNT = 33

const outputDirectory = fileURLToPath(new URL('../src/data/map/', import.meta.url))

function download(url) {
  return new Promise((resolve, reject) => {
    get(url, (response) => {
      if (response.statusCode && response.statusCode >= 300 && response.statusCode < 400 && response.headers.location) {
        response.resume()
        download(response.headers.location).then(resolve, reject)
        return
      }
      if (response.statusCode !== 200) {
        reject(new Error(`Download failed with HTTP ${response.statusCode ?? 'unknown'}`))
        response.resume()
        return
      }
      const chunks = []
      response.on('data', (chunk) => chunks.push(chunk))
      response.on('end', () => resolve(Buffer.concat(chunks)))
      response.on('error', reject)
    }).on('error', reject)
  })
}

function digest(algorithm, bytes, encoding = 'hex') {
  return createHash(algorithm).update(bytes).digest(encoding)
}

function assertEqual(actual, expected, label) {
  if (actual !== expected) throw new Error(`${label} mismatch: expected ${expected}, received ${actual}`)
}

const archive = await download(SOURCE_URL)
assertEqual(digest('sha1', archive), EXPECTED_SHA1, 'SHA-1')
assertEqual(digest('sha256', archive), EXPECTED_SHA256, 'SHA-256')
assertEqual(`sha512-${digest('sha512', archive, 'base64')}`, EXPECTED_INTEGRITY, 'npm integrity')

const temporaryDirectory = mkdtempSync(join(tmpdir(), 'ming-china-map-'))
try {
  const archivePath = join(temporaryDirectory, 'china-2.0.0.tgz')
  writeFileSync(archivePath, archive)
  execFileSync('tar', ['-xzf', 'china-2.0.0.tgz'], { cwd: temporaryDirectory })

  const moduleText = readFileSync(join(temporaryDirectory, 'package', 'index.js'), 'utf8')
  const sourceMap = JSON.parse(moduleText.replace(/^export default\s+/, ''))
  assertEqual(sourceMap.viewBox, EXPECTED_VIEWBOX, 'viewBox')
  assertEqual(sourceMap.locations.length, EXPECTED_FEATURE_COUNT, 'feature count')

  const generated = `/**
 * Generated by scripts/vendor-china-reference-map.mjs from @svg-maps/china@2.0.0.
 * Modern geographic reference only; this is not historical administrative geometry.
 * Source geometry is preserved without simplification in its original 0 0 774 569 viewBox.
 */
export interface ChinaReferenceFeature {
  readonly id: string
  readonly name: string
  readonly path: string
}

export const CHINA_REFERENCE_BASEMAP = ${JSON.stringify({
    id: 'china-modern-reference-svg-maps-2.0.0',
    label: 'Modern China geographic reference',
    viewBox: sourceMap.viewBox,
    sourcePackage: '@svg-maps/china',
    sourceVersion: '2.0.0',
    license: 'CC-BY-4.0',
    features: sourceMap.locations,
  }, null, 2)} as const satisfies {
  readonly id: string
  readonly label: string
  readonly viewBox: string
  readonly sourcePackage: string
  readonly sourceVersion: string
  readonly license: string
  readonly features: readonly ChinaReferenceFeature[]
}
`

  writeFileSync(join(outputDirectory, 'chinaReferenceBasemap.ts'), generated)
  writeFileSync(
    join(outputDirectory, 'CHINA_REFERENCE_BASEMAP_LICENSE.md'),
    readFileSync(join(temporaryDirectory, 'package', 'LICENSE.md')),
  )
  console.log(`Vendored ${sourceMap.locations.length} modern reference features from ${SOURCE_URL}`)
  console.log(`Output directory: ${outputDirectory}`)
} finally {
  rmSync(temporaryDirectory, { recursive: true, force: true })
}
